function main() {
  const files = fs.readdirSync(POSTS_DIR).filter((f) => f.endsWith('.md'))
  let done = 0
  const missing = []

  for (const file of files) {
    const filePath = path.join(POSTS_DIR, file)
    let content = fs.readFileSync(filePath, 'utf8')
    const slug = Number(content.match(/^slug:\s*(\d+)/m)?.[1])
    const desc = descriptions[slug]

    if (!desc) {
      missing.push(file)
      continue
    }

    const newDescLine = `description: ${JSON.stringify(desc)}`

    if (/^description:\s*.*$/m.test(content)) {
      content = content.replace(/^description:.*$/m, newDescLine)
    } else {
      content = content.replace(/^(slug:\s*\d+.*)$/m, `$1\n${newDescLine}`)
    }

    fs.writeFileSync(filePath, content)
    done++
  }

  if (missing.length) {
    console.warn(`⚠️ 缺少 description 映射：${missing.join(', ')}`)
  }
  console.log(`完成！共更新 ${done} 篇文章的 description。`)
}

